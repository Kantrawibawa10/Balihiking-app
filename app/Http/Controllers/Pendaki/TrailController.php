<?php

namespace App\Http\Controllers\Pendaki;

use App\Http\Controllers\Controller;
use App\Models\HikingTrail;
use Illuminate\View\View;

class TrailController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | SHOW TRAIL
    |--------------------------------------------------------------------------
    */

    public function show(
        HikingTrail $trail
    ): View {
        /*
        |--------------------------------------------------------------------------
        | VALIDASI JALUR AKTIF
        |--------------------------------------------------------------------------
        */

        if (! $trail->is_active) {
            abort(
                404,
                'Jalur pendakian tidak tersedia.'
            );
        }


        /*
        |--------------------------------------------------------------------------
        | LOAD RELATIONS
        |--------------------------------------------------------------------------
        */

        $trail->load([

            /*
            |--------------------------------------------------------------------------
            | MOUNTAIN
            |--------------------------------------------------------------------------
            */

            'mountain',


            /*
            |--------------------------------------------------------------------------
            | CHECKPOINTS
            |--------------------------------------------------------------------------
            */

            'checkpoints' => function (
                $query
            ) {
                $query
                    ->select([
                        'id',
                        'hiking_trail_id',
                        'name',
                        'latitude',
                        'longitude',
                        'elevation_m',
                        'type',
                    ])
                    ->orderBy(
                        'id'
                    );
            },


            /*
            |--------------------------------------------------------------------------
            | GUIDES
            |--------------------------------------------------------------------------
            */

            'guides' => function (
                $query
            ) {
                $query
                    ->where(
                        'is_active',
                        true
                    )
                    ->orderBy(
                        'sort_order'
                    )
                    ->orderBy(
                        'id'
                    );
            },

        ]);


        /*
        |--------------------------------------------------------------------------
        | RETURN VIEW
        |--------------------------------------------------------------------------
        */

        return view(
            'pendaki.trails.show',
            compact(
                'trail'
            )
        );
    }
}